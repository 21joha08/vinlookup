package com.example.vinlookup.dto;

public class VehicleResponse {

    private String vehicleBrandName;
    private String vehicleModel;
    private String vehicleDrive;
    private String chassisNo;
    private String yearOfBuilt;
    private String countryOfOrigin;
    private String vehicleType;
    private String vehicleColor;

    public String getVehicleBrandName() {
        return vehicleBrandName;
    }

    public void setVehicleBrandName(String vehicleBrandName) {
        this.vehicleBrandName = vehicleBrandName;
    }

    public String getVehicleModel() {
        return vehicleModel;
    }

    public void setVehicleModel(String vehicleModel) {
        this.vehicleModel = vehicleModel;
    }

    public String getVehicleDrive() {
        return vehicleDrive;
    }

    public void setVehicleDrive(String vehicleDrive) {
        this.vehicleDrive = vehicleDrive;
    }

    public String getChassisNo() {
        return chassisNo;
    }

    public void setChassisNo(String chassisNo) {
        this.chassisNo = chassisNo;
    }

    public String getYearOfBuilt() {
        return yearOfBuilt;
    }

    public void setYearOfBuilt(String yearOfBuilt) {
        this.yearOfBuilt = yearOfBuilt;
    }

    public String getCountryOfOrigin() {
        return countryOfOrigin;
    }

    public void setCountryOfOrigin(String countryOfOrigin) {
        this.countryOfOrigin = countryOfOrigin;
    }

    public String getVehicleType() {
        return vehicleType;
    }

    public void setVehicleType(String vehicleType) {
        this.vehicleType = vehicleType;
    }

    public String getVehicleColor() {
        return vehicleColor;
    }

    public void setVehicleColor(String vehicleColor) {
        this.vehicleColor = vehicleColor;
    }
}
